
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from lime.lime_tabular import LimeTabularExplainer

#---- 1. Explainability With Lime
def explain_customer_with_lime(
    model,
    X_train: pd.DataFrame,
    customer_features: pd.DataFrame,
    feature_names=None,
    num_features: int = 10,
    num_samples: int = 5000,
    output_dir=None,
    show: bool = False,
) -> dict:
    """
    Generate a local LIME explanation for one customer.

    Parameters
    ----------
    model:
        Fitted classification model with predict_proba().

    X_train:
        Training features used to represent the training distribution.
        Use the same engineered features and order as the model.

    customer_features:
        A DataFrame containing exactly one customer's features.

    feature_names:
        Expected feature names in model order.

    num_features:
        Maximum number of features displayed in the explanation.

    num_samples:
        Number of perturbed samples generated by LIME.

    output_dir:
        Optional directory for saving the plot and CSV.

    show:
        Whether to display the plot immediately.

    Returns
    -------
    dict
        Prediction, probabilities, LIME explanation,
        contribution table, and output paths.
    """

    # 1. Validate inputs
    if not isinstance(X_train, pd.DataFrame):
        raise TypeError("X_train must be a pandas DataFrame.")

    if not isinstance(customer_features, pd.DataFrame):
        raise TypeError(
            "customer_features must be a pandas DataFrame."
        )

    if X_train.empty:
        raise ValueError("X_train is empty.")

    if len(customer_features) != 1:
        raise ValueError(
            "customer_features must contain exactly one row."
        )

    if not hasattr(model, "predict_proba"):
        raise TypeError(
            "The model must support predict_proba()."
        )

    expected_features = (
        list(feature_names)
        if feature_names is not None
        else list(X_train.columns)
    )

    if len(expected_features) != len(set(expected_features)):
        raise ValueError("Feature names contain duplicates.")

    missing_train = [
        name for name in expected_features
        if name not in X_train.columns
    ]
    missing_customer = [
        name for name in expected_features
        if name not in customer_features.columns
    ]

    if missing_train or missing_customer:
        raise ValueError(
            f"Missing training features: {missing_train}; "
            f"missing customer features: {missing_customer}"
        )

    if num_features < 1 or num_samples < 1:
        raise ValueError(
            "num_features and num_samples must be positive."
        )

    # Keep exact model feature order
    X_background = X_train[expected_features].copy()
    customer = customer_features[expected_features].copy()

    # Convert to numeric arrays and validate
    try:
        background_array = X_background.to_numpy(dtype=float)
        customer_array = customer.to_numpy(dtype=float)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "All model features must be numeric."
        ) from exc

    if not np.isfinite(background_array).all():
        raise ValueError(
            "Training features contain missing or infinite values."
        )

    if not np.isfinite(customer_array).all():
        raise ValueError(
            "Customer features contain missing or infinite values."
        )

    if (
        hasattr(model, "n_features_in_")
        and len(expected_features) != model.n_features_in_
    ):
        raise ValueError(
            f"Model expects {model.n_features_in_} features, "
            f"but received {len(expected_features)}."
        )

    # 2. Create the LIME explainer using training data
    class_names = [
        str(label) for label in model.classes_
    ]

    lime_explainer = LimeTabularExplainer(
        training_data=background_array,
        feature_names=expected_features,
        class_names=class_names,
        mode="classification",
        discretize_continuous=True,
        random_state=42,
    )

    # 3. Generate explanation for the selected customer
    explanation = lime_explainer.explain_instance(
        data_row=customer_array[0],
        predict_fn=model.predict_proba,
        labels=(
            [int(np.flatnonzero(model.classes_ == 1)[0])]
            if 1 in model.classes_
            else [0]
        ),
        num_features=min(num_features, len(expected_features)),
        num_samples=num_samples,
    )

    # 4. Get model prediction and probabilities
    probabilities = model.predict_proba(customer)[0]
    predicted_class = model.predict(customer)[0]

    probability_dict = {
        str(label): float(probability)
        for label, probability
        in zip(model.classes_, probabilities)
    }

    # 5. Get LIME contributions for the churn class
    if 1 in model.classes_:
        churn_class_index = int(
            np.flatnonzero(model.classes_ == 1)[0]
        )
    else:
        churn_class_index = 0

    lime_weights = explanation.as_list(
        label=churn_class_index
    )

    contribution_table = pd.DataFrame(
        lime_weights,
        columns=["Feature_Condition", "LIME_Weight"],
    )

    contribution_table["Direction"] = np.where(
        contribution_table["LIME_Weight"] > 0,
        "Supports churn",
        np.where(
            contribution_table["LIME_Weight"] < 0,
            "Opposes churn",
            "Neutral",
        ),
    )

    # 6. Generate the LIME plot
    figure = explanation.as_pyplot_figure(
        label=churn_class_index
    )

    figure.tight_layout()

    plot_path = None
    csv_path = None

    # 7. Save artifacts if an output directory is supplied
    if output_dir is not None:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        plot_path = (
            output_dir / "lime_customer_explanation.png"
        )
        csv_path = (
            output_dir / "lime_customer_contributions.csv"
        )

        figure.savefig(
            plot_path,
            dpi=150,
            bbox_inches="tight",
        )

        contribution_table.to_csv(
            csv_path,
            index=False,
        )

    if show:
        plt.show()
    else:
        plt.close(figure)

    # 8. Return reusable results
    return {
        "prediction": int(predicted_class),
        "prediction_label": (
            "Churn" if predicted_class == 1 else "No Churn"
        ),
        "class_probabilities": probability_dict,
        "explanation": explanation,
        "contributions": contribution_table,
        "figure": figure,
        "plot_path": plot_path,
        "csv_path": csv_path,
    }


#---- 2. Comparing lime and Shap
def compare_lime_with_shap(
    lime_result: dict,
    shap_explanation,
    customer_idx: int,
    top_n: int = 10,
) -> pd.DataFrame:
    """
    Compare LIME and SHAP feature contributions
    for the same customer.

    SHAP values should be from a modern SHAP Explanation
    object covering the same feature set and row order.
    """

    if top_n < 1:
        raise ValueError("top_n must be positive.")

    if shap_explanation.values.ndim != 2:
        raise ValueError(
            "Expected SHAP values with shape (rows, features)."
        )

    if not 0 <= customer_idx < shap_explanation.values.shape[0]:
        raise IndexError("Invalid customer_idx.")

    shap_features = list(shap_explanation.feature_names)

    if not shap_features:
        raise ValueError(
            "SHAP explanation must include feature names."
        )

    shap_row = pd.DataFrame({
        "Feature": shap_features,
        "SHAP_Value": shap_explanation.values[customer_idx],
    })

    lime_table = lime_result["contributions"].copy()

    # LIME conditions may look like "Recency > 200".
    # Match each condition to its original feature name.
    lime_feature_names = []
    for condition in lime_table["Feature_Condition"]:
        matching_features = [
            feature for feature in shap_features
            if condition == feature
            or condition.startswith(feature + " ")
        ]

        lime_feature_names.append(
            max(matching_features, key=len)
            if matching_features
            else None
        )

    lime_table["Feature"] = lime_feature_names
    lime_table = lime_table.dropna(subset=["Feature"])

    # Aggregate LIME weights when multiple conditions
    # refer to the same feature.
    lime_table = lime_table.groupby(
        "Feature", as_index=False
    )["LIME_Weight"].sum()

    comparison = shap_row.merge(
        lime_table,
        on="Feature",
        how="outer",
    ).fillna({
        "SHAP_Value": 0.0,
        "LIME_Weight": 0.0,
    })

    comparison["Absolute_SHAP"] = (
        comparison["SHAP_Value"].abs()
    )
    comparison["Absolute_LIME"] = (
        comparison["LIME_Weight"].abs()
    )

    comparison = comparison.sort_values(
        "Absolute_SHAP",
        ascending=False,
    ).head(top_n)

    return comparison.reset_index(drop=True)
